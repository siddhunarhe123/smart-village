class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem("smartvillage_lang") || "mr";
  }

  init() {
    this.setLanguage(this.currentLang, false);
    this.bindLanguageSwitchers();
  }

  getLang() {
    return this.currentLang;
  }

  setLanguage(lang, triggerEvent = true) {
    if (!["en", "mr", "hi"].includes(lang)) lang = "mr";
    this.currentLang = lang;
    localStorage.setItem("smartvillage_lang", lang);
    document.documentElement.lang = lang;

    this.translateDOM();
    this.updateActiveSwitcher(lang);

    if (triggerEvent) {
      window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
    }
  }

  translate(key) {
    const dict = I18N_DICTIONARY[this.currentLang] || I18N_DICTIONARY.mr;
    return dict[key] || I18N_DICTIONARY.mr[key] || I18N_DICTIONARY.en[key] || key;
  }

  translateData(item, fieldPrefix) {
    if (!item) return "";
    const lang = this.currentLang;
    if (lang === "en" && item[fieldPrefix + "En"]) return item[fieldPrefix + "En"];
    if (lang === "hi" && item[fieldPrefix + "Hi"]) return item[fieldPrefix + "Hi"];
    if (lang === "mr" && item[fieldPrefix + "Mr"]) return item[fieldPrefix + "Mr"];
    return item[fieldPrefix + "Mr"] || item[fieldPrefix + "En"] || item[fieldPrefix + "Hi"] || item[fieldPrefix] || "";
  }

  translateCategory(category) {
    if (!category) return "";
    const c = category.toLowerCase().trim();
    if (c.includes("water") || c.includes("पाणी") || c.includes("जल")) return this.translate("catWaterSupply");
    if (c.includes("street") || c.includes("लाइट") || c.includes("दिवा") || c.includes("दिवे")) return this.translate("catStreetLights");
    if (c.includes("sanitation") || c.includes("drainage") || c.includes("सांडपाणी") || c.includes("स्वच्छता") || c.includes("नाली")) return this.translate("catSanitation");
    if (c.includes("road") || c.includes("रस्ते") || c.includes("सड़क")) return this.translate("catRoads");
    if (c.includes("health") || c.includes("आरोग्य") || c.includes("स्वास्थ्य")) return this.translate("catHealth");
    if (c.includes("agri") || c.includes("कृषी") || c.includes("किसान") || c.includes("फसल")) return this.translate("catAgriculture");
    if (c.includes("house") || c.includes("घरकूल") || c.includes("आवास")) return this.translate("catHousing");
    if (c.includes("solar") || c.includes("सौर")) return this.translate("catCleanEnergy");
    return category;
  }

  translateStatus(status) {
    if (!status) return "";
    const s = status.toLowerCase().trim();
    if (s === "submitted" || s.includes("दाखल") || s.includes("दर्ज")) return this.translate("statusSubmitted");
    if (s === "under review" || s.includes("पडताळणी") || s.includes("समीक्षा")) return this.translate("statusUnderReview");
    if (s === "in progress" || s.includes("प्रगती") || s.includes("प्रगति")) return this.translate("statusInProgress");
    if (s === "resolved" || s.includes("निवारण") || s.includes("समाधान")) return this.translate("statusResolved");
    if (s === "rejected" || s.includes("नाकार") || s.includes("खारिज")) return this.translate("statusRejected");
    return status;
  }

  translateTrend(trend) {
    if (!trend) return "";
    const t = trend.toLowerCase().trim();
    if (t === "up" || t === "तेजी") return this.translate("trendBullish");
    if (t === "down" || t === "मंदी") return this.translate("trendBearish");
    return this.translate("trendStable");
  }

  translateDOM() {
    // 1. Text content with preservation of icons/SVG
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const translation = this.translate(key);
      if (translation) {
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
          if (el.type === "submit" || el.type === "button") {
            el.value = translation;
          }
        } else {
          // If element has a child icon (i or svg), preserve it!
          const icon = el.querySelector("i, svg");
          if (icon) {
            const iconClone = icon.cloneNode(true);
            el.innerHTML = "";
            el.appendChild(iconClone);
            el.appendChild(document.createTextNode(" " + translation));
          } else {
            el.textContent = translation;
          }
        }
      }
    });

    // 2. Placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      const translation = this.translate(key);
      if (translation) el.placeholder = translation;
    });

    // 3. Titles / tooltips
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      const translation = this.translate(key);
      if (translation) el.title = translation;
    });

    // 4. Values (e.g. submit buttons)
    document.querySelectorAll("[data-i18n-value]").forEach((el) => {
      const key = el.getAttribute("data-i18n-value");
      const translation = this.translate(key);
      if (translation) el.value = translation;
    });
  }

  bindLanguageSwitchers() {
    document.querySelectorAll(".lang-select-btn, [data-lang]").forEach((btn) => {
      btn.addEventListener("click", (e) => {
        const selectedLang = btn.getAttribute("data-lang");
        if (selectedLang) {
          e.preventDefault();
          this.setLanguage(selectedLang, true);
        }
      });
    });
  }

  updateActiveSwitcher(lang) {
    document.querySelectorAll(".lang-select-btn, [data-lang]").forEach((btn) => {
      if (btn.getAttribute("data-lang") === lang) {
        btn.classList.add("active", "fw-bold");
      } else {
        btn.classList.remove("active", "fw-bold");
      }
    });

    document.querySelectorAll("#currentLangDisplay, #currentLangLabel, .current-lang-text").forEach((el) => {
      const labels = { mr: "मराठी", hi: "हिंदी", en: "English" };
      el.textContent = labels[lang] || "मराठी";
    });
  }
}

// Global i18n instance
window.i18n = new I18nManager();
window.t = (key) => window.i18n.translate(key);
window.getLang = () => window.i18n.getLang();
window.tData = (item, prefix) => window.i18n.translateData(item, prefix);
window.setLanguage = (lang) => window.i18n.setLanguage(lang, true);
window.tCategory = (cat) => window.i18n.translateCategory(cat);
window.tStatus = (status) => window.i18n.translateStatus(status);
window.tTrend = (trend) => window.i18n.translateTrend(trend);

document.addEventListener("DOMContentLoaded", () => {
  window.i18n.init();
});
